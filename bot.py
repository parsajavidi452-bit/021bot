    # ════════════════════════════════════════════════════════════
    def _add_xp(self, uid: str, amount: int = 5) -> Optional[int]:
        """XP اضافه می‌کنه، اگه لول آپ شد عدد لول جدید برمیگردونه"""
        old_lvl = self._get_level(uid)
        self.xp[uid] = self.xp.get(uid, 0) + amount
        new_lvl = self._get_level(uid)
        return new_lvl if new_lvl > old_lvl else None

    def _get_level(self, uid: str) -> int:
        xp_val = self.xp.get(uid, 0)
        lvl = 0
        for i, thresh in enumerate(self.level_thresholds):
            if xp_val >= thresh:
                lvl = i
        return lvl

    def _xp_bar(self, uid: str) -> str:
        lvl = self._get_level(uid)
        xp_val = self.xp.get(uid, 0)
        curr = self.level_thresholds[lvl]
        nxt  = self.level_thresholds[min(lvl+1, len(self.level_thresholds)-1)]
        if nxt == curr:
            return "MAX ██████████"
        progress = (xp_val - curr) / (nxt - curr)
        filled = int(progress * 10)
        return "█" * filled + "░" * (10 - filled)

