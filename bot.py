# Run
# ════════════════════════════════════════════════════════════════
def run_bot_instance():
    bot_configs = []
    if os.path.exists("bots_config.json"):
        try:
            with open("bots_config.json","r",encoding="utf-8") as f:
                cfg_list = json.load(f)
            for entry in cfg_list:
                r = entry.get("room_id","").strip()
                t = entry.get("api_token","").strip()
                a = entry.get("admin_username","parsapr").strip()
                if r and t:
                    bot_configs.append({"room_id":r,"api_token":t,"admin_username":a})
            if bot_configs:
                print(f"✅ {len(bot_configs)} بات از bots_config.json")
        except Exception as e:
            print(f"⚠️ bots_config.json error: {e}")

    if not bot_configs:
        try:
            import tiba
            bot_configs.append({
                "room_id": tiba.ROOM_ID,
                "api_token": tiba.HIGHRISE_API_TOKEN,
                "admin_username": tiba.ADMIN_USERNAME,
            })
        except ImportError: pass

    if not bot_configs:
        r = os.environ.get("ROOM_ID","")
        t = os.environ.get("HIGHRISE_API_TOKEN","")
        a = os.environ.get("ADMIN_USERNAME","parsapr")
        if r and t:
            bot_configs.append({"room_id":r,"api_token":t,"admin_username":a})

    if not bot_configs:
        print("❌ هیچ توکنی پیدا نشد!")
        return

    definitions = []
    for idx, cfg in enumerate(bot_configs):
        bot = HighriseBot(
            room_id=f"{cfg['room_id']}_{idx}",
            bot_admins=[cfg['admin_username']],
            api_token=cfg['api_token'],
            real_room_id=cfg['room_id']
        )
        definitions.append(BotDefinition(bot, cfg['room_id'], cfg['api_token']))
        print(f"🚀 بات {idx+1}: روم {cfg['room_id'][:8]}... | ادمین: {cfg['admin_username']}")

    print(f"▶️ شروع {len(definitions)} بات...")

    async def _run_with_reconnect():
        while True:
            try:
                await run_bot(definitions)
            except Exception as e:
                print(f"⚠️ قطع اتصال: {e} — ریکانکت در 5 ثانیه...")
                await asyncio.sleep(5)

    arun(_run_with_reconnect())


if __name__ == "__main__":
    start_keep_alive()
    run_bot_instance()
