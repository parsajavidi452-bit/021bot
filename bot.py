    # ════════════════════════════════════════════════════════════
    # on_whisper (ویسپر داخل روم)
    # ════════════════════════════════════════════════════════════
    async def on_whisper(self, user: User, message: str) -> None:
        try:
            user_id  = user.id
            username = user.username
            self.user_name_cache[user_id] = username
            if is_admin(user):
                self.admin_user_ids.add(user_id)
            print(f"📩 ویسپر از {username}: {message}")

            # ── اگه ادمینه و دستور داد، توی روم اجرا کن ──
            if is_admin(user) and message.strip().startswith("!"):
                cmd = message.strip()
                await self.highrise.send_whisper(user_id, f"✅ دستور در روم اجرا میشه: {cmd[:40]}")
                await self.on_chat(user, cmd)
                return

            reply = self._find_pv_reply(message)
            if not reply:
                hist = self.whisper_history.get(user_id, [])
                hist.append({"role":"user","content":message})
                reply = await self._ai_reply(hist, username)
                hist.append({"role":"assistant","content":reply})
                self.whisper_history[user_id] = hist[-20:]
            await self.highrise.send_whisper(user_id, reply)
        except Exception as e:
            print(f"❌ on_whisper error: {e}")

    # ════════════════════════════════════════════════════════════
    # on_message (DM / اینباکس)
    # ════════════════════════════════════════════════════════════
    async def on_message(self, user_id: str, conversation_id: str, is_new_conversation: bool) -> None:
        try:
            result = await self.highrise.webapi.get_messages(conversation_id)
            messages_list = getattr(result, "messages", None)
            if not messages_list: return
            last_msg   = messages_list[0]
            content    = (getattr(last_msg,"content","") or "").strip()
            sender_id  = (getattr(last_msg,"sender_id","") or "")
            if not content: return
            if sender_id and sender_id != user_id: return  # loop guard

            # ── اگه ادمینه و دستور داد، توی روم اجرا کن ──
            # از admin_user_ids که هنگام join/whisper پر میشه استفاده میکنیم
            sender_name = self.user_name_cache.get(user_id, "")
            if (user_id in self.admin_user_ids and content.strip().startswith("!")):
                # یه User ساده میسازیم برای is_admin
                class _FakeUser:
                    def __init__(self, uid, uname):
                        self.id = uid
                        self.username = uname
                fake = _FakeUser(user_id, sender_name)
                await self.highrise.webapi.send_message(
                    conversation_id,
                    f"✅ دستور در روم اجرا میشه: {content.strip()[:40]}", "text"
                )
                await self.on_chat(fake, content.strip())
                return

            reply = None
            if is_new_conversation:
                reply = "سلام! 🤍 خوش اومدی! چیزی نیاز داری بگو 😊"
            if not reply:
                hist = self.whisper_history.get(user_id, [])
                hist.append({"role":"user","content":content})
                reply = await self._ai_reply(hist, user_id)
                hist.append({"role":"assistant","content":reply})
                self.whisper_history[user_id] = hist[-20:]
            await self.highrise.webapi.send_message(conversation_id, reply, "text")
        except AttributeError as e:
            print(f"⚠️ webapi unavailable: {e}")
        except Exception as e:
            print(f"❌ on_message error: {e}")

    # ════════════════════════════════════════════════════════════
    # PV Reply — جستجوی کلیدواژه توی پیام خصوصی
    # ════════════════════════════════════════════════════════════
    def _find_pv_reply(self, message: str) -> Optional[str]:
        """پیام رو توی PV_RESPONSES جستجو می‌کنه، اگه پیدا کرد جواب برمیگردونه"""
        if not message:
            return None
        msg_lower = message.strip().lower()
        # اول دنبال تطابق دقیق می‌گرده
        for keyword, reply in PV_RESPONSES.items():
            if keyword.lower() == msg_lower:
                return reply
        # بعد دنبال کلیدواژه‌ای که توی پیام باشه می‌گرده
        for keyword, reply in PV_RESPONSES.items():
            if keyword.lower() in msg_lower:
                return reply
        return None

    # ════════════════════════════════════════════════════════════
    # AI reply (Gemini → fallback)
    # ════════════════════════════════════════════════════════════
    async def _ai_reply(self, history: list, username: str) -> str:
        gemini_key = os.environ.get("GEMINI_API_KEY")
        if gemini_key and history:
            try:
                system_msg = (
                    "تو یه دوست مهربان فارسی‌زبان توی بازی Highrise هستی. "
                    "کوتاه (حداکثر 2 جمله) و صادق جواب بده. فقط فارسی."
                )
                contents = [
                    {"role":"user" if m["role"]=="user" else "model",
                     "parts":[{"text":m["content"]}]}
                    for m in history
                ]
                payload = {
                    "system_instruction": {"parts":[{"text":system_msg}]},
                    "contents": contents,
                    "generationConfig": {"maxOutputTokens":150,"temperature":0.8}
                }
                url = (
                    "https://generativelanguage.googleapis.com/v1beta/models/"
                    f"gemini-2.0-flash:generateContent?key={gemini_key}"
                )
                resp = requests.post(url, json=payload, timeout=12)
                if resp.status_code == 200:
                    return resp.json()["candidates"][0]["content"]["parts"][0]["text"].strip()
            except Exception as e:
                print(f"Gemini error: {e}")
        msg_low = (history[-1]["content"] if history else "").lower()
        if any(w in msg_low for w in ["غمگین","ناراحت","گریه","تنها","خسته"]):
            return random.choice(["❤️ می‌فهمم، بگو چی شده؟","🤍 تنها نیستی.","💙 اینجام."])
        if any(w in msg_low for w in ["خوشحال","عالی","ممنون","مرسی"]):
            return random.choice(["😊 خوشحالم!","🌟 آفرین!","❤️ خوش اومدی!"])
        return random.choice(["🤍 اینجام، بگو.","😊 گوش میدم.","💙 کمکت می‌کنم."])

