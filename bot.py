def get_command_reply(message: str):
    """
    فقط وقتی پیام با ! شروع بشه بررسی می‌کنه (مثلاً !سلام).
    برای جلوگیری از اسپم زیاد توی روم و پیوی، به پیام‌های آزاد جواب نمی‌ده.
    """
    if not message or not message.startswith("!"):
        return None
    cmd = message[1:].strip().lower()
    if not cmd:
        return None
    for keyword, reply in PV_RESPONSES.items():
        if keyword.lower() == cmd or keyword.lower() in cmd:
            return reply
    return None

