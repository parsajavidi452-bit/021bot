    # Multi-loop spam system (جدید)
    # ════════════════════════════════════════════════════════════
    def start_spam_loop(self, name: str, message: str, interval: float):
        """شروع یه لوپ اسپم با اسم مشخص (interval زیر 60 ثانیه)"""
        self.stop_spam_loop(name)
        task = asyncio.create_task(self._named_spam_loop(name, message, interval))
        self.spam_loops[name] = {'task': task, 'message': message, 'interval': interval}

    def stop_spam_loop(self, name: str):
        """توقف یه لوپ اسپم با اسم مشخص"""
        loop_info = self.spam_loops.pop(name, None)
        if loop_info and loop_info.get('task'):
            loop_info['task'].cancel()

    def stop_all_spam_loops(self):
        """توقف همه لوپ‌ها"""
        for name in list(self.spam_loops.keys()):
            self.stop_spam_loop(name)

    async def _named_spam_loop(self, name: str, message: str, interval: float):
        try:
            while name in self.spam_loops:
                await self.highrise.chat(message)
                await asyncio.sleep(interval)
        except asyncio.CancelledError:
            pass
        except Exception as e:
            print(f"SpamLoop [{name}] error: {e}")

