    # ════════════════════════════════════════════════════════════
    # on_user_join
    # ════════════════════════════════════════════════════════════
    async def on_user_join(self, user: User, position) -> None:
        try:
            self.total_visitors += 1
            username = user.username
            user_id  = user.id

            # کش اسم
            self.user_name_cache[user_id] = username
            if is_admin(user):
                self.admin_user_ids.add(user_id)

            # ── روم قفل: غیر ادمین‌ها کیک بشن ──
            if self.room_locked and not is_admin(user):
                await self.highrise.chat(f"🔒 {username}، روم قفله! بعداً بیا.")
                try: await self.highrise.moderate_room(user_id, "kick")
                except Exception: pass
                return

            if user_id in self.banned_users:
                await self.highrise.chat(f"🚫 {username} بن است!")
                try: await self.highrise.moderate_room(user_id, "kick")
                except Exception: pass
                return

            # Check birthday
            if user_id in self.birthdays:
                today = datetime.datetime.now().strftime("%d/%m")
                if self.birthdays[user_id] == today:
                    await self.highrise.chat(f"🎂🎉 {username} امروز تولدشه! تبریک! 🎈")

            if username.lower() in self.vip_users:
                await self.highrise.chat(f"👑✨ {username} VIP ما، خوش اومدی! ✨👑")
                try:
                    await self.highrise.send_emote("emote-fireworks")
                    await asyncio.sleep(1)
                    await self.highrise.send_emote("dance-kawai")
                except Exception: pass
            else:
                welcome = self.welcome_text.replace("{user}", username)
                await self.highrise.chat(welcome)
                try: await self.highrise.send_emote("emote-wave")
                except Exception: pass

            # بونوس ورود
            join_bonus = 10
            self._add_gold(user_id, join_bonus)
            new_lvl = self._add_xp(user_id, 10)
            if new_lvl is not None:
                await self.highrise.chat(
                    f"🎉 {username} لول آپ! → لول {new_lvl} 🏆"
                )

        except Exception as e:
            print(f"❌ on_user_join error: {e}")

    # ════════════════════════════════════════════════════════════
    # on_user_leave
    # ════════════════════════════════════════════════════════════
    async def on_user_leave(self, user: User) -> None:
        try:
            uid = user.id
            uname = user.username
            if uid in self.auto_emotes:
                self.auto_emotes[uid].cancel()
                del self.auto_emotes[uid]
            self._release_dance(uid)
            self.muted_users.discard(uid)
            # unfreeze اگه فریز بود
            self.frozen_users.discard(uid)
            if uid in self.freeze_tasks:
                self.freeze_tasks[uid].cancel()
                del self.freeze_tasks[uid]
            # ذخیره آخرین بازدید (فوری برای مقاومت در برابر کرش)
            self.last_seen[uname.lower()] = datetime.datetime.now().strftime("%Y/%m/%d %H:%M")
            self._save_data()
            await self.highrise.chat(f"👋 {uname} رفت. دوباره برگرد 🤍")
        except Exception as e:
            print(f"❌ on_user_leave error: {e}")

