    # Highrise WebAPI — مدیریت مودریتور روم
    # ════════════════════════════════════════════════════════════
    async def _set_room_mod(self, target_user_id: str, add: bool) -> bool:
        """
        اضافه/حذف مودریتور روم از طریق Highrise REST API.
        add=True → مود کردن | add=False → آنمود کردن
        Returns True اگه موفق بشه.
        """
        room = self._real_room_id
        token = self._api_token
        if not room or not token:
            print("⚠️ _set_room_mod: room_id یا api_token خالیه")
            return False
        try:
            url = f"https://webapi.highrise.game/rooms/{room}/moderators/{target_user_id}"
            headers = {
                "Authorization": token,
                "Content-Type": "application/json"
            }
            method = "post" if add else "delete"
            loop = asyncio.get_event_loop()
            # requests رو به صورت non-blocking اجرا میکنیم
            resp = await loop.run_in_executor(
                None,
                lambda: getattr(requests, method)(url, headers=headers, timeout=10)
            )
            print(f"🔧 room mod API → {resp.status_code}: {resp.text[:100]}")
            return resp.status_code in (200, 201, 204)
        except Exception as e:
            print(f"❌ _set_room_mod error: {e}")
            return False

    # ════════════════════════════════════════════════════════════
    # Anti-spam
    # ════════════════════════════════════════════════════════════
    def _check_spam(self, uid: str) -> bool:
        """True اگه اسپمر باشه"""
        now = time.time()
        ts  = self.msg_timestamps.get(uid, [])
        ts  = [t for t in ts if now - t < 5]
        ts.append(now)
        self.msg_timestamps[uid] = ts
        return len(ts) > 8   # بیشتر از 8 پیام در 5 ثانیه = اسپم

