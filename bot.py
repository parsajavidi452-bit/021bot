    async def _unmute_after(self, uid: str, seconds: int):
        await asyncio.sleep(seconds)
        self.muted_users.discard(uid)

    async def _quiz_timeout(self, uid: str):
        await asyncio.sleep(30)
        if uid in self.active_quiz:
            q = self.active_quiz.pop(uid)
            await self.highrise.chat(f"⏰ وقت سوال تموم شد! جواب: {q['answer']}")

    async def _typing_timeout(self):
        await asyncio.sleep(60)
